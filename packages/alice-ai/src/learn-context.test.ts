import assert from 'node:assert/strict';
import test from 'node:test';
import { learnContextFor, markSecurityNotice, markTutorialChoices, registerLearnContextProvider, securityNoticeIn, tutorialChoicesIn, tutorialChoicesInTurn, withoutClosingList, withoutRestatedNotice } from './learn-context.ts';

test('surfaces without Learn do not add course context', async () => {
  assert.equal(await learnContextFor('Bitcoin'), null);
});

test('Learn receives the resolved response language and keeps its size bound', async () => {
  registerLearnContextProvider(async (query, options) => {
    assert.equal(query, 'Comment sauvegarder ma phrase de récupération ?');
    assert.equal(options?.targetLanguage, 'fr');
    return { label: 'Recovery', excerpt: `${'x'.repeat(900)}\n\n${'y'.repeat(4_500)}` };
  });
  const result = await learnContextFor('Comment sauvegarder ma phrase de récupération ?', { targetLanguage: 'fr' });
  assert.equal(result?.excerpt, 'x'.repeat(900));
});

test('missing, blank or failed Learn context does not fail retrieval', async () => {
  for (const provider of [
    async () => null,
    async () => ({ label: 'Empty', excerpt: '  ' }),
    async () => { throw new Error('Pack unavailable'); },
  ]) {
    registerLearnContextProvider(provider);
    assert.equal(await learnContextFor('Bitcoin'), null);
  }
});

test('a slow Learn provider remains bounded and a late answer is ignored', async t => {
  t.mock.timers.enable({ apis: ['setTimeout'] });
  let finish!: (value: { label: string; excerpt: string }) => void;
  registerLearnContextProvider(() => new Promise(resolve => { finish = resolve; }));
  const result = learnContextFor('Bitcoin');
  t.mock.timers.tick(1_500);
  assert.equal(await result, null);
  finish({ label: 'Late', excerpt: 'Too late for this turn.' });
});


test('an oversized single Learn paragraph is omitted instead of losing its qualifier', async () => {
  registerLearnContextProvider(async () => ({ label: 'Safety', excerpt: `${'Claim '.repeat(1_000)}Only if all required conditions hold.` }));
  assert.equal(await learnContextFor('Bitcoin'), null);
});

test('a tutorial warning framed for the turn is found again in what the turn sends', () => {
  const framed = markSecurityNotice('**⚠️ AVIS** Ne générez pas de seed.\nDéplacez vos fonds.');
  assert.match(framed, /^\[Security notice of this tutorial\. The app shows it above your answer: do not repeat it, and write nothing that contradicts it\.\]\n\*\*⚠️ AVIS\*\* Ne générez pas de seed\. Déplacez vos fonds\.\n\[End of security notice\]$/);
  assert.equal(securityNoticeIn([{ role: 'system', content: 'rules' }, { role: 'user', content: `Learn\n${framed}\n\n## Étapes` }]), '**⚠️ AVIS** Ne générez pas de seed. Déplacez vos fonds.');
  assert.equal(securityNoticeIn([{ role: 'assistant', content: framed }, { role: 'user', content: 'Bonjour' }]), null, 'an earlier answer is not a source');
  assert.equal(markSecurityNotice('  '), '');
});

test('a paragraph that only says the warning again is dropped, a step that mentions the risk stays', () => {
  const notice = "**⚠️ URGENT SECURITY DISCLOSURE (July 2026) — Coldcard wallets are actively being drained.** A firmware bug in the seed generation of Coldcard devices allows attackers to find your seed phrase without any action on your part. **All Coldcard models are affected: Mk3, Mk4, Mk5, and Q.** On July 30, 2026, roughly 594 BTC were stolen from about 500 wallets, and the attack is still ongoing. Only wallets generated with the dice roll method are considered safe, and only if you rolled at least 50 dice. If you don't know, don't remember, or aren't sure how your seed was generated, treat it as compromised and **move your funds immediately** to a wallet whose seed was not generated on a Coldcard. Follow Coinkite's official announcements.";
  const steps = [
    '**Coldcard configuration** means setting up the device so it can safely generate a recovery phrase.',
    '1. **Select a PIN code** – choose a numeric PIN (4-12 digits).\n2. **Generate a recovery phrase** – pick the **Dice Roll** method. Roll at least 50 dice to generate a seed that is not vulnerable to the known bug. Write the 24-word phrase down on paper and store it securely.',
  ];
  const cloud = "**Important security notice** – A firmware bug discovered in July 2026 lets attackers recover seeds generated by Coldcard's default method. Only wallets created with the Dice-Roll method (≥ 50 dice) are considered safe. If you're unsure how your seed was generated, treat the device as compromised and move any funds immediately to a wallet whose seed was created elsewhere.";
  const local = '*Note: The provided security notice states that all Coldcard models are currently affected by a firmware bug that could allow attackers to find your seed phrase. If you are unsure how your seed was generated, treat it as compromised and move your funds immediately to a wallet whose seed was not generated on a Coldcard.*';
  const followUp = 'What would you like to explore next: detailed steps for the firmware update, or a walk-through of Dice-Roll seed generation?';
  assert.equal(withoutRestatedNotice([...steps, cloud, followUp].join('\n\n'), notice), [...steps, followUp].join('\n\n'));
  assert.equal(withoutRestatedNotice([...steps, local].join('\n\n'), notice), steps.join('\n\n'));
  assert.equal(withoutRestatedNotice(local, notice), local, 'an answer is never emptied');
});

test('the tutorials a name stands for are framed, read back whole and listed by the app', () => {
  const framed = markTutorialChoices([
    { name: 'Trezor Model One', description: 'Configurer et utiliser le hardware wallet Model One' },
    { name: 'Trezor Safe 3', description: 'Configurer et utiliser le hardware wallet Safe 3' },
    { name: 'Trezor Shamir Backup' },
  ]);
  assert.ok(framed.split('\n').includes('Trezor Safe 3'), 'each name is alone on its line, as a source label');
  assert.deepEqual(tutorialChoicesIn(`Définition.\n\n${framed}\n\n[Current turn intent]`), ['Trezor Model One', 'Trezor Safe 3', 'Trezor Shamir Backup']);
  assert.deepEqual(tutorialChoicesIn(framed.slice(0, framed.lastIndexOf('['))), [], 'a list the budget cut is not shown');
  assert.deepEqual(tutorialChoicesInTurn([{ role: 'assistant', content: framed }, { role: 'user', content: 'Trezor' }]), [], 'an earlier answer is not a source');
  assert.equal(tutorialChoicesInTurn([{ role: 'user', content: framed }]).length, 3);

  const question = 'Trezor est une marque de hardware wallets.\n\nLequel t’intéresse ?';
  assert.equal(withoutClosingList(`${question}\n* Configurer le Trezor Model One\n* Trezor Safe 3\n`), question);
  assert.equal(withoutClosingList(`${question}\n\n1. Trezor Model One\n2. Trezor Safe 3`), question);
  assert.equal(withoutClosingList(question), question);
  assert.equal(withoutClosingList('- Trezor Model One\n- Trezor Safe 3'), '- Trezor Model One\n- Trezor Safe 3', 'an answer is never emptied');
});
